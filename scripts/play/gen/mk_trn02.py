"""W6 fix #2: Boot Camp 2 (TRN02) won with real orders only (no cheats).

The Drill Sergeant's chain: move the MCV out and deploy it, build power, a
refinery and barracks, then "Build a squad of GIs" (objective 6 -- needs
W6-02-15: a trained GI is tracked as E1, not its Image= GI). The two Red Team
waves come at the base; the GIs (deployed at the entrance) beat them. Then
the GI army walks to the red base and destroys every building
('PlayerWin' = all RedTeam buildings destroyed).

Run from the repo root: python scripts/play/gen/mk_trn02.py [OUT.play]
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen import P  # noqa: E402

HEADER = """# W6 fix #2: Boot Camp 2 (TRN02) won with real orders only (no cheats).
# Generated by scripts/play/gen/mk_trn02.py -- edit the generator, not this file.
# MCV out + deploy, power, refinery, barracks, a squad of GIs (objective 6:
# the build event sees E1 since W6-02-15), beat the Red Team waves at the
# base, then the GIs destroy every RedTeam building ('PlayerWin').
set render_every 6000
set max_frames 40000
set on_quit continue
set campaign trn02t.MAP GDI
until 60 scene == campaign-load
click start
until 300 scene == game
waituntil 900 units(0,AMCV) >= 1
wait 200
click unit 0:AMCV:0
click cell 26 38
waituntil 900 moving(0) == 0
wait 60
click unit 0:AMCV:0
key d
waituntil 600 buildings(0,GACNST) >= 1
wait 60
"""

# The Red Team base (house 1): the map's Allied-type base, plus whatever the
# Red Team AI builds (defences first).
RED = ["NALASR", "GAPILE", "NAHAND", "GAPOWR", "GACNST", "GAREFN", "NAWEAP", "NAPOWR", "NARADR", "NACNST"]


def main(out):
    p = P(HEADER)
    p.build("GAPOWR").build("GAREFN").build("GAPILE")
    p.add("until 600 buildings(0,GAPILE) >= 1", "wait 60")
    p.train("E1", 2, 6)
    p.add("waituntil 3000 units(0,E1) >= 6", "dump")
    p.train("E1", 2, 10)
    g = "outcome == RUNNING"
    # Hold the base until both Red Team waves are spent.
    for k in range(10):
        p.add("let tw = f", "until 300 outcome != RUNNING or f >= $tw+299")
        if k % 3 == 2:
            p.add(f"if {g} then dump", "if outcome == WON then end expect WON")
    p.train("E1", 2, 14, guard=True)
    p.add("until 4000 units(0,E1) >= 22 or outcome != RUNNING", "dump", "shot trn02_army")
    # March on the red base: attack each building type in turn.
    for r in range(12):
        for b in RED:
            p.select_types(["E1"])
            # R3: since an attack on a building holds at weapon range, the
            # squad stands in front of its target; ':near' clicks a footprint
            # point no GI covers (a click on a selected GI deploys it).
            p.add(f"if {g} and buildings(1,{b}) > 0 then click building 1:{b}:near", "click xy 500 400 right")
            p.add("let tw = f", "until 300 outcome != RUNNING or f >= $tw+299", "if outcome == WON then end expect WON")
        p.train("E1", 2, 5, guard=True)
        p.add(f"if {g} then dump", "if outcome == WON then end expect WON")
    p.add("shot trn02_final", "until 3000 outcome != RUNNING", "dump", "end expect WON")
    p.save(out)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "scripts/play/m-trn02-real.play")
