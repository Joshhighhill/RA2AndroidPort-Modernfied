"""R3: SOV08 (Washington) V3 siege -- best attempt, does NOT win yet (Easy).

Usage: python scripts/play/gen/mk_sov08.py OUT.play   (no m-sov08-real.play is
committed: the run ends RUNNING). See docs/gap/wave4/05-mission-sequences.md
"R3 status" for the full log of attempts.

What works (each step proven in a run):
  * Base: SMCV to (59,97), power, barracks, 2 sentry guns, refinery, war
    factory, radar, 4 Tesla Coils, Battle Lab, 2nd refinery/factory; V3s queue
    and build normally (the W6 "only one V3" was not a queue/harness bug: four
    clicks queue four V3s; that attempt ran out of money / lost the factory).
  * The White House (4x4, concrete) is in range of a V3 up to 20 cells from
    its centre (Range 18 + (4+4)*64 leptons). The only sites in the map's
    LocalSize are inside the walled pocket west of it (x 83-92, y 13-29) and
    the road in front of Vlad2's war factory (88,31): flak (94,28)/(106,28)
    cover all of them, but the clone's flak kills few rockets (most land).
  * The pocket holds two Vlad2 Conscript garrisons (Garrison1/2 teams, script
    46 -> CANEWY12 (88,26) and CAWASH07 (88,20)). 10 V3s at (73,35)/(77,31)
    destroy both from outside their reach in ~3000 frames, then the Tesla
    Coils at (94,23) and (97,28) from (78,30) -- possible only since the R3
    building-hold fix (V3s ordered at a building beyond 18 cells used to
    drive up to it through Vlad2's base).
What stops it: the 16 freed garrison Conscripts, Vlad2's Shock Troopers,
Rhinos and Flak Track (98,24) counter-attack the pocket; the Apocalypse
escort (no anti-infantry weapon) chases them into the remaining Teslas or
loses to the Shock Troopers, and the V3s die before the White House is seen.
Next step: an anti-infantry escort (Desolators / Flak Tracks) that does not
strip the base (taking the starting Desolators lost the base), or attrition
waves before the siege.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mk_sov07 import P7  # noqa: E402

HEADER = """# R3: SOV08 played with real orders only (no cheats). Generated by
# scripts/play/gen/mk_sov08.py -- edit the generator, not this file.
set render_every 6000
set on_quit continue
set max_frames 90000
set campaign sov08u.MAP Nod 0
until 60 scene == campaign-load
click start
until 300 scene == game
until 3000 units(0,SMCV) >= 1
wait 15
"""


def main(out):
    p = P7(HEADER)
    p.select_types(["APOC", "HTNK", "DESO", "E2"])
    p.add("click cell 57 101", "wait 10", "click xy 500 400 right", "click unit 0:SMCV", "click cell 59 97",
          "wait 30", "until 900 sel_moving == 0", "wait 10", "key d", "until 900 built(0,NACNST) >= 1",
          "click xy 500 400 right", "dump")
    p.build("NAPOWR").build("NAHAND").build("NALASR", tab=1, cat="defense").build("NAREFN")
    p.build("NALASR", tab=1, cat="defense").build("NAWEAP")
    p.build("NAPOWR").build("NARADR")
    p.add("dump")
    g = "outcome == RUNNING"
    p.build("TESLA", tab=1, cat="defense").build("NAPOWR").build("TESLA", tab=1, cat="defense")
    p.build("NAPOWR").build("NAREFN").build("NATECH").build("NAPOWR").build("NAWEAP").build("NAPOWR")
    p.build("TESLA", tab=1, cat="defense").build("NAPOWR").build("TESLA", tab=1, cat="defense").build("NAPOWR")
    p.add("dump")

    def keep_harvesters():
        c = f"{g} and harvesters(0) < 2 and cameo(HARV) == 1"
        p.add(f"if {c} then click tab:3", f"if {c} then click cameo:HARV")

    p.train("HTK", 3, 2)
    p.train("APOC", 3, 6)
    p.train("V3", 3, 10)
    for _ in range(40):
        keep_harvesters()
        p.add(f"if units(0,V3) < 9 and {g} then wait 600")
    p.add("dump")
    army = ["APOC"]

    def sel(types):
        """Select every unit of these types; a first unit standing where the
        camera cannot centre (the map's LocalSize edge) is skipped."""
        p.add("click xy 500 400 right")
        for t in types:
            for n in range(4):
                p.add(f"if selected == 0 and units(0,{t}) > {n} then click unit 0:{t}:{n} soft")
        for t in types[1:]:
            p.add(f"if units(0,{t}) > 0 then click unit 0:{t}:0 shift soft")
        p.add("key t", "key t")

    def move_click(x, y):
        """A move order only: a click that would land on an enemy (attack
        cursor) becomes an explicit attack, which pursues without a leash."""
        for (cx, cy) in [(x, y), (x + 1, y), (x, y + 1), (x - 1, y), (x, y - 1), (x + 1, y + 1)]:
            p.add(f"move cell {cx} {cy}", "wait 1",
                  f"if {g} and cursor_name == move and sel_moving == 0 then click cell {cx} {cy}", "wait 2")

    def go(types, pts, w=3000):
        sel(types)
        for (x, y) in pts:
            move_click(x, y)
            p.add("wait 30", f"until {w} sel_moving == 0 or outcome != RUNNING")
        p.add("click xy 500 400 right", "dump")

    def hit(types, target, cond, n, w=200, hold=None):
        """Re-issue an attack on `target` every w frames while cond holds;
        `hold` (types, cell) re-parks a second group in between."""
        for k in range(n):
            sel(types)
            p.add(f"if {g} and {cond} then click {target}", "click xy 500 400 right",
                  f"if {g} and {cond} then wait {w}")
            if hold:
                sel(hold[0])
                move_click(*hold[1])
                p.add("click xy 500 400 right")
            if k % 3 == 2:
                p.add(f"if {g} then dump")

    def scout(pts):
        p.add("click xy 500 400 right", "click unit 0:HTK:0", "if selected == 0 then click unit 0:APOC:0")
        for (x, y) in pts:
            p.add(f"if selected > 0 then click cell {x} {y}", "wait 30", "until 1500 sel_moving == 0")
        p.add("click xy 500 400 right", "dump")

    # 1. the V3s (18 cells) take down the two Conscript garrisons of the
    #    pocket west of the White House from outside their reach; the tanks
    #    wait further back (they chase whatever shoots at them into the base).
    go(army, [(64, 62), (66, 46), (70, 38)])
    go(["V3"], [(64, 62), (66, 46), (73, 35)])
    # one Apocalypse (Sight 6, heavy armour) looks into the pocket
    p.add("click xy 500 400 right", "click unit 0:APOC:0")
    for (x, y) in [(80, 28), (84, 23), (72, 36)]:
        p.add(f"if units(0,APOC) > 0 then click cell {x} {y}", "wait 30", "until 1500 sel_moving == 0")
    p.add("click xy 500 400 right", "dump")
    go(army, [(74, 36)])
    sel(army)
    p.add("key g", "click xy 500 400 right")   # area guard beside the V3s
    hit(["V3"], "cell 88 26", "buildings(4,CANEWY12) > 0", 20, 200)
    go(["V3"], [(77, 31)])
    go(army, [(76, 33)])
    sel(army)
    p.add("key g", "click xy 500 400 right")
    hit(["V3"], "cell 89 21", "buildings(4,CAWASH07) > 0", 20, 200)
    p.add("dump")
    # 1b. and the Tesla Coil at (94,23) that covers the pocket's east half
    go(["V3"], [(78, 30)])
    hit(["V3"], "building 2:TESLA:near", "outcome == RUNNING", 10, 200)
    p.add("dump")
    # 2. the tanks crush the freed garrison Conscripts and hold the west end
    #    of the pocket (normal guard: 10 cells from the Tesla Coils); the
    #    Flak Track looks over the wall at the White House; the V3s follow.
    go(army, [(76, 32), (80, 29), (84, 25)])
    scout([(86, 21), (91, 17), (84, 22)])
    go(["V3"], [(80, 28), (84, 23)])
    hit(["V3"], "building 4:CAWASH01:0", "outcome == RUNNING", 40, 200, hold=(army, (84, 25)))
    p.add("until 1500 outcome != RUNNING", "end expect WON")
    p.save(out)


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "m-sov08-real.play"))
