"""P2: SOV07 (Chronosphere) won with real player orders only (no cheats).

Defend the Battle Lab against the Allied chrono waves until the 'Massive Last
Attempt' (2550 s) arms 'PlayerWin1', then hunt down every BadGuy1 unit.
The build: power, refinery, war factory, then Flak Tracks first (the 400 s
Rocketeers go for the Battle Lab and Tesla Coils cannot hit air), Apocalypse
tanks (the player owns a Battle Lab), a second war factory, radar, four Tesla
Coils; afterwards one Apocalypse + one Flak Track per round, the army
rallied beside the lab. After the last wave the army attacks the remaining
BadGuy1 units until the map's own trigger chain declares the win.

Run from the repo root: python scripts/play/gen/mk_sov07.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen import P  # noqa: E402


class P7(P):
    def build(self, bid, tab=0, wait=2400, cat="structure", count_key=None):
        """gen.P.build with every wait guarded so it never reports a failure:
        under attack a structure can be momentarily unbuildable (power, a lost
        prerequisite) or lost in the same frames it is placed; the build is
        then skipped or the wait simply ends."""
        self.add(f"let n_{bid} = built(0,{bid})",
                 f"let tc_{bid} = f",
                 f"until 900 can_build({bid}) == 1 or f >= $tc_{bid}+899",
                 f"let ok_{bid} = can_build({bid})",
                 f"if $ok_{bid} == 1 then click tab:{tab}",
                 f"if $ok_{bid} == 1 then click cameo:{bid}",
                 f"let tq_{bid} = f",
                 f"until {wait} queue_ready({cat}) == 1 or $ok_{bid} == 0 or f >= $tq_{bid}+{wait - 1}",
                 f"if queue_ready({cat}) == 1 then click cameo:{bid}",
                 f"if placing == 1 then place auto",
                 f"let t_{bid} = f",
                 f"until 600 built(0,{bid}) > $n_{bid} or $ok_{bid} == 0 or f >= $t_{bid}+599")
        return self


HEADER = """# P2: SOV07 (Chronosphere) won with real orders only (no cheats).
# Generated by scripts/play/gen/mk_sov07.py -- edit the generator, not this
# file. Flak Tracks + Apocalypse tanks + Tesla Coils hold the Battle Lab
# through every chrono wave; after the 2550 s 'Massive Last Attempt' the army
# hunts the last BadGuy1 units and 'PlayerWin1' -> 'PlayerWin2' -> VICTORY.
set render_every 6000
set on_quit continue
set max_frames 60000
# W6 fix #2: Easy. Since W6-02-11 idle units engage at weapon range + 1 (not Sight)
# and W6-02-16 enemy teams set out at full strength; on Normal the defence no longer
# holds. On Easy the player reloads x0.8 and every computer house x1.2 (W6-02-01..03).
set campaign sov07s.MAP Nod 0
until 60 scene == campaign-load
click start
until 300 scene == game
wait 30
until 1500 input_locked == 0
"""


def main(out):
    p = P7(HEADER)
    p.build("NAPOWR").build("NAREFN").build("NAWEAP")
    p.train("HTK", 3, 4)
    p.add("until 2500 units(0,HTK) >= 3")
    p.select_types(["HTK"]).add("click cell 77 68")
    p.train("APOC", 3, 3)
    p.build("NAPOWR").build("NAWEAP").build("NARADR").build("NAPOWR")
    p.train("APOC", 3, 3, guard=True)
    p.build("TESLA", tab=1, cat="defense").build("NAPOWR").build("TESLA", tab=1, cat="defense").build("NAPOWR")
    p.build("TESLA", tab=1, cat="defense").build("TESLA", tab=1, cat="defense").build("NAREFN")
    # Two more plants: since P4's `place` retries a refused placement on the
    # next candidate, every Tesla Coil gets placed and four coils outdraw the
    # plants (drain 485 > 450 at f=10856: low power, coils offline -> LOST).
    p.build("NAPOWR").build("NAPOWR")
    p.add("dump")
    army = ["APOC", "HTNK"]
    g = "outcome == RUNNING"
    for r in range(60):
        p.train("APOC", 3, 1, guard=True)
        p.train("HTK", 3, 1, guard=True)
        p.select_types(army)
        p.add(f"if {g} then click cell 77 70", f"if {g} then wait 500")
        if r % 5 == 4:
            p.add(f"if {g} then dump")
    for r in range(40):
        p.select_types(army)
        p.add(f"if {g} and units(1) > 0 then click unit 1:*:0", f"if {g} then wait 300")
        if r % 5 == 4:
            p.add(f"if {g} then dump")
    p.add("until 9000 outcome == WON", "end expect WON")
    p.save(out)


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "m-sov07-real.play"))
