"""P2: SOV09 (Mexico) real-order proof -- the opening and the first blackout step.

Real player orders only (no cheats). What it proves, in order:
  1. the Yuris (paradropped, Africans = clone house 6) are pulled back at
     battle control and survive the 100 s 'Yuri's are Dead' arm;
  2. Yuri 1 mind-controls the x=37 IFV patrol, which LEAVES its script team
     (FootClass::SetOwningHouse FUN_004DBDE0) and obeys the player;
  3. Yuri 0 walks round the west side of the Alliance compound (out of the
     door GIs' reach), mind-controls the British engineer, and the engineer
     captures the Alliance barracks ('Captured Barracks' hands it to the
     player); two attack dogs from it clear the door GIs;
  4. Yuri 0 waits north of the American base until the upper-right wall
     patrol is at its far end, mind-controls the 'SEAL Power Plant' SEAL,
     and the SEAL plants C4 on the north power plant: American output
     1000 -> 800 (power plants deliver health-scaled output, FUN_0044E7B0).

The mission is NOT won here: the remaining four plants sit inside the walled
Prism compound; see docs/gap/wave4/05-mission-sequences.md "P2 status".
Run from the repo root: python scripts/play/gen/mk_sov09.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen import P  # noqa: E402

HEADER = """# P2: SOV09 played with real orders only (no cheats). Generated by
# scripts/play/gen/mk_sov09.py -- edit the generator, not this file.
# Opening (W4-SQ): the Yuris arrive by paradrop plane and are pulled back at
# battle control (65 s) so 'Yuri's are Dead' (armed at 100 s) never fires.
# Then: Yuri 1 takes the IFV patrol, Yuri 0 takes the British engineer from
# the west (it captures the Alliance barracks), two dogs clear the door GIs,
# and Yuri 0 takes the power-plant SEAL, whose C4 blacks out one of the five
# American power plants (output 1000 -> 800).
set render_every 900
set on_quit continue
set campaign sov09u.MAP Nod
until 60 scene == campaign-load
click start
until 300 scene == game
until 600 airborne(6) >= 1
until 2000 campaign_frame >= 980
click unit 6:YURI:0
click cell 36 74
click unit 6:YURI:1
click cell 37 74
until 600 campaign_frame >= 1150
click unit 6:YURI:0
click cell 36 75
click unit 6:YURI:1
click cell 37 75
"""


def pick(p, spec):
    """Right-click (deselect), then select one unit: clicking a friendly
    transport with a Yuri selected would order the Yuri inside it."""
    return p.add("click xy 500 400 right", f"click unit {spec}")


def order(p, spec, target, wait=None):
    pick(p, spec).add(f"click {target}")
    if wait:
        p.add(f"wait {wait}")
    return p


def yuri_go(p, n, x, y, w=2500):
    order(p, f"6:YURI:{n}", f"cell {x} {y}", 20)
    return p.add(f"until {w} umov(6,YURI,{n}) == 0")


def main(out):
    p = P(HEADER)
    # 2. Yuri 1 takes the x=37 IFV patrol as it comes south, parks it west.
    p.add("until 1500 ucy(1,FV,1) >= 70")
    order(p, "6:YURI:1", "cell 39 77", 20)
    order(p, "6:YURI:1", "unit 1:FV:1")
    p.add("until 300 units(6,FV) >= 1")
    order(p, "6:FV:0", "cell 27 64")
    order(p, "6:YURI:1", "cell 26 68")
    p.add("assert units(6,FV) >= 1", "assert units(6,YURI) >= 2")
    # 3. Yuri 0: round the west side, take the engineer, capture the barracks.
    yuri_go(p, 0, 26, 74, 1500)
    yuri_go(p, 0, 25, 47, 1500)
    order(p, "6:YURI:0", "unit 5:SENGINEER:0")
    p.add("until 900 units(6,SENGINEER) >= 1")
    order(p, "6:SENGINEER:0", "building 2:GAPILE:0")
    order(p, "6:YURI:0", "cell 25 66")
    p.add("until 900 buildings(0,GAPILE) >= 1",
          "until 900 can_build(DOG) == 1", "click tab:2", "click cameo:DOG", "click cameo:DOG",
          "until 900 units(0,DOG) >= 2", "until 900 units(2,E1) <= 5",
          "assert buildings(0,GAPILE) >= 1", "assert units(2,E1) <= 5", "dump", "shot barracks")
    # 4. Yuri 0 north; the SEAL patrol's C4 takes out the north power plant.
    for (x, y) in [(27, 43), (40, 37), (63, 41), (64, 39)]:
        yuri_go(p, 0, x, y)
    p.add("until 3000 ucx(1,DOG,5) >= 71 and ucx(1,DOG,6) >= 71 and "
          "ucx(1,GHOST,11) >= 63 and ucx(1,GHOST,11) <= 66")
    order(p, "6:YURI:0", "unit 1:GHOST:11")
    p.add("until 300 units(6,GHOST) >= 1")
    order(p, "6:GHOST:0", "cell 65 52")
    # 62,36 (was 64,37): with the mind-control shot no longer damaging, the
    # timing shifts and a wandering civilian stands on 64,38 -- the click
    # became an attack order that traded the SEAL for the civilian.
    yuri_go(p, 0, 62, 36)
    p.add("until 900 power_out(1) <= 800",
          "assert power_out(1) <= 800", "assert units(6,YURI) >= 2",
          "assert outcome == RUNNING", "dump", "shot blackout1", "end expect RUNNING")
    p.save(out)


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "m-sov09-real.play"))
