"""P3: ALL06 real-order win -> ../m-all06-real.play (see the script header)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen import P
import json
VAR = json.loads(os.environ.get("A6VAR", "{}"))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "m-all06-real.play")
p = P("""# P3: ALL06 (Pentagon) WON with real orders only (no cheats). Generated by gen/mk_all06.py.
# Win = DestroyedAll(BadGuy1) + DestroyedAll(BadGuy2) (Insignificant/DontScore objects do not count).
# The landed AMCV deploys; power, 3 refineries, barracks, 3 war factories; Grizzlies massed to 55 at
# (104,148) then sweep BadGuy2 (Tesla Coils first, then the nearest building); regroup to 70 at (99,75)
# and sweep BadGuy1 the same way while the factories keep the army topped up; then hunt the last units.
# W6 (R1): played on EASY (`set campaign ... GDI 0`). With the wave-6 engine (per-house difficulty
# handicap, full-strength teams, AI anger/income) Normal no longer holds: the AI houses wear the start
# force down (13 units left at f6000, was 22), BadGuy1 fields 35 units by f12000 (was 23), and BadGuy2
# rebuilds its Tesla Coil and fields Shock Troopers/Rhinos that destroy the 58-tank sweep (58 -> 0).
# Easy = player ROF x0.8, every computer house x1.2 [Easy]/[Difficult]. A sweep click is sent only
# while a Grizzly is selected (the first Grizzly click can land on a building and select nothing).
# fv-b (R3 hold-at-range, R-210 height gate, fv-a return-to-anchor): the 70-Grizzly sweep died at
# BadGuy1's Tesla/Sentry line (Shock Troopers + Rhinos) and the run ended RUNNING with ~50k credits
# unspent. Now the army masses to 70 before BadGuy2 and 90 before BadGuy1, and every sweep step
# re-targets Rhinos / Shock Troopers within 9 cells of the army before the next structure.
set render_every 3000
set on_quit continue
set max_frames 200000
set campaign ALL06u.MAP GDI 0
until 60 scene == campaign-load
click start
until 300 scene == game
wait 30
until 3000 input_locked == 0
until 3000 carried(0) == 0
click unit 0:AMCV
key d
waituntil 300 built(0,GACNST) >= 1
# P4: when the unloaded troops crowd every legal spot around the beach (the
# ring search finds none -- "cannot deploy"), drive the AMCV to the open
# ground just north-west and deploy there.
if built(0,GACNST) == 0 and units(0,AMCV) == 1 then click unit 0:AMCV
if built(0,GACNST) == 0 and units(0,AMCV) == 1 then click cell 91 160
if built(0,GACNST) == 0 and units(0,AMCV) == 1 then wait 200
if built(0,GACNST) == 0 and units(0,AMCV) == 1 then key d
until 900 built(0,GACNST) >= 1
""")
for b in ["GAPOWR", "GAREFN", "GAPILE", "GAPOWR", "GAWEAP"]:
    p.build(b)
p.train("MTNK", 3, 10, guard=True)
for b in ["GAREFN", "GAPOWR", "GAWEAP", "GAPOWR", "GAREFN", "GAWEAP", "GAPOWR"]:
    p.build(b)
SEL = lambda g: [f"if {g} and units(0,MTNK) > 0 then click unit 0:MTNK:0",
                 f"if {g} and selected_type(MTNK) == 0 and units(0,MTNK) > 1 then click unit 0:MTNK:1",
                 f"if {g} then key t", f"if {g} then key t"]
def mass(n, stage):
    for r in range(12):
        p.train("MTNK", 3, 10, guard=True)
        p.add(f"waituntil 1500 units(0,MTNK) >= {n}")
        p.add(*SEL(f"units(0,MTNK) < {n}"), f"if units(0,MTNK) < {n} then click cell {stage}", "dump")
    p.add(*SEL("outcome == RUNNING"), f"click cell {stage}", "wait 600", "dump")
UNIT_R = VAR.get("unit_r", 9)
UNIT_FIRST = VAR.get("unit_first", ["HTNK", "SHK"])


def sweep(h, iters, first):
    for k in range(iters):
        g = f"outcome == RUNNING and buildings({h}) > 0"
        gs = g + " and selected_type(MTNK) > 0"
        p.add(*SEL(g),
              f"if {gs} and buildings({h},{first}) > 0 then click building {h}:{first}:near",
              f"if {gs} and buildings({h},{first}) == 0 then click building {h}:*:near")
        # fv-b: Shock Troopers / Rhinos within UNIT_R cells of the army are
        # shot first (the later click wins); left alone they destroyed the
        # 70-Grizzly sweep at BadGuy1's Tesla line once R3 made the tanks
        # stop at weapon range from each structure.
        for t in UNIT_FIRST:
            p.add(f"if {gs} and sel_near({h},{t}) < {UNIT_R} then click unit {h}:{t}:near soft")
        p.add(f"if {g} then wait 250", f"if {g} then dump")
        if k % 2 == 1: p.train("MTNK", 3, 8, guard=True)
mass(VAR.get("mass2", 70), "104 148")
p.add("shot staged2")
sweep(2, 120, "TESLA")
p.add("shot bg2_done", "dump")
mass(VAR.get("mass1", 90), "99 75")
p.add("shot staged1")
sweep(1, 160, "TESLA")
for k in range(60):   # hunt the last units (AllToHunt sends most of them to us)
    for h in (1, 2):
        g = f"outcome == RUNNING and units({h}) > 0"
        p.add(*SEL(g), f"if {g} then click unit {h}:*:0 soft", f"if {g} then wait 200", f"if {g} then dump")
p.add("until 3000 outcome == WON", "dump", "end expect WON")
p.save(OUT)
