#!/usr/bin/env python3
"""Extract the original game's FastMath lookup tables into engine/gen/orig_math_tables.inc.

Net L0 (docs/gap/net/03-sim-bitexact.md §2.2, 04-engine-lockstep.md N4-01).

The original gamemd.exe never calls the CRT sqrt/sin/cos/atan2: every
transcendental is a Westwood FastMath lookup into float32 tables that live in
INITIALISED .data of the executable. The table builders that exist in the
binary (0x4CAE40 sqrt, 0x4CB000 sin, 0x4CB120 asin, 0x4CB1E0 tan, 0x4CB280 atan)
have NO references (Ghidra xref census, D:\\ra2-re\\l0, log callers1.txt) -- they
are dead code, so the tables are never rebuilt at startup and cannot be
re-derived by running the original's generation code. The tables also do not
equal any correctly-rounded closed form (checked below with --check-formula:
thousands of 1-ulp differences per table), so they are dumped once, verbatim.

The engine never needs gamemd.exe: this script is run ONCE by a developer and
its output (engine/gen/orig_math_tables.inc) is committed.

Layout in the binary (build SHA-1 7BE4E550..., the RE build; addresses per
docs/gap/net/03-sim-bitexact.md §1):

  0x84E004  sin   float32[10241]   8192 steps/turn + 2048 so cos = sin[i+0x800]
  0x858014  asin  float32[4097]    asin(j/2048 - 1), read at base - 4*idx
  0x85C024  tan   float32[4097]    4096 steps/turn
  0x860034  atan  float32[4097]    atan(i * step)
  0x864038  atan step  float32     (static; the dead builder 0x4CB280 would recompute it)
  0x86403C  sqrt  int32[16384]     23-bit mantissas, index = exp parity | top 13 mantissa bits

Usage:
  python tools/extract_orig_math_tables.py "D:/Red Alert 2/gamemd.exe" engine/gen/orig_math_tables.inc
  python tools/extract_orig_math_tables.py --check-formula "D:/Red Alert 2/gamemd.exe"
"""
import hashlib
import math
import struct
import sys

EXPECTED_SHA1 = "7be4e5508655f8af482ab3ff5965d196e1b6b6c7"

TABLES = [
    # name, va, count, C type
    ("kOrigSinTab", 0x84E004, 10241, "std::uint32_t"),
    ("kOrigAsinTab", 0x858014, 4097, "std::uint32_t"),
    ("kOrigTanTab", 0x85C024, 4097, "std::uint32_t"),
    ("kOrigAtanTab", 0x860034, 4097, "std::uint32_t"),
    ("kOrigSqrtTab", 0x86403C, 16384, "std::int32_t"),
]

# Scalar constants the FastMath routines read (all verified against the
# disassembly of 0x4CAB60..0x4CAE01, dis1.txt). Emitted as raw bit patterns so
# the engine reproduces them exactly.
SCALARS = [
    # name, va, size(4=float bits,8=double bits), meaning
    ("kOrigAtanStepBits", 0x864038, 4, "atan table step (float)"),
    ("kOrigSinScaleBits", 0x8213C0, 4, "sin: x * 2607.5945f (8192*2 / 2pi)"),
    ("kOrigCosScaleBits", 0x8213C4, 4, "cos: x * 2607.5945f"),
    ("kOrigTanScaleBits", 0x7E7970, 8, "tan: x * 651.898... (4096 / 2pi)"),
    ("kOrigAsinScaleBits", 0x7E7978, 4, "asin/acos: (x + 1) * -2048.0f"),
    ("kOrigOneFBits", 0x7E1AC8, 4, "1.0f"),
    ("kOrigHalfPiDBits", 0x7E1820, 8, "acos: pi/2 (double) - asin"),
    ("kOrigPiDBits", 0x7E34D0, 8, "atan2: pi (double) - t when x < 0"),
    ("kOrigHalfPiFBits", 0x7E797C, 4, "atan beyond table / atan2(y>0, 0): pi/2 (float)"),
    ("kOrigNegHalfPiFBits", 0x7E7980, 4, "atan2(y<=0, 0): -pi/2 (float)"),
    ("kOrigNegOneDBits", 0x7E3900, 8, "sqrt(x<0): x * -1.0"),
    ("kOrigFtolCw", 0x821D80, 4, "_ftol FPU control word (0x0E7F: truncate, PC53)"),
]


class Pe:
    def __init__(self, path):
        self.data = open(path, "rb").read()
        self.sha1 = hashlib.sha1(self.data).hexdigest()
        d = self.data
        pe = struct.unpack_from("<I", d, 0x3C)[0]
        nsec = struct.unpack_from("<H", d, pe + 6)[0]
        optsz = struct.unpack_from("<H", d, pe + 20)[0]
        self.base = struct.unpack_from("<I", d, pe + 24 + 28)[0]
        self.secs = []
        o = pe + 24 + optsz
        for _ in range(nsec):
            vsz, va, rsz, rptr = struct.unpack_from("<IIII", d, o + 8)
            self.secs.append((va + self.base, vsz, rptr, rsz))
            o += 40

    def read(self, va, n):
        for sva, vsz, rptr, rsz in self.secs:
            if sva <= va < sva + max(vsz, rsz):
                off = va - sva
                if off + n > rsz:
                    raise ValueError("0x%x+%d is not initialised file data" % (va, n))
                return self.data[rptr + off:rptr + off + n]
        raise ValueError("0x%x not in any section" % va)


def emit(pe, out_path):
    lines = [
        "// GENERATED by tools/extract_orig_math_tables.py -- DO NOT EDIT.",
        "// The original gamemd.exe FastMath tables, copied verbatim from initialised",
        "// .data of the RE build (SHA-1 %s)." % pe.sha1,
        "// See engine/orig_math.hpp for the routines that read them and the",
        "// script header for the extraction rationale (the in-binary builders are dead code).",
        "// Included ONLY by engine/orig_math.cpp.",
        "",
    ]
    for name, va, size, meaning in SCALARS:
        raw = pe.read(va, size)
        if size == 4:
            v = struct.unpack("<I", raw)[0]
            lines.append("constexpr std::uint32_t %s = 0x%08xu;   // [0x%X] %s" % (name, v, va, meaning))
        else:
            v = struct.unpack("<Q", raw)[0]
            lines.append("constexpr std::uint64_t %s = 0x%016xull;   // [0x%X] %s" % (name, v, va, meaning))
    lines.append("")
    for name, va, count, ctype in TABLES:
        vals = struct.unpack("<%dI" % count, pe.read(va, 4 * count))
        lines.append("// [0x%X] %d entries" % (va, count))
        lines.append("alignas(64) const %s %s[%d] = {" % (ctype, name, count))
        for i in range(0, count, 8):
            chunk = vals[i:i + 8]
            if ctype == "std::int32_t":
                cells = ["%d" % struct.unpack("<i", struct.pack("<I", v))[0] for v in chunk]
            else:
                cells = ["0x%08xu" % v for v in chunk]
            lines.append("    " + ", ".join(cells) + ",")
        lines.append("};")
        lines.append("")
    with open(out_path, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", out_path)


def check_formula(pe):
    rf = lambda x: struct.unpack("<f", struct.pack("<f", x))[0]
    f32 = lambda va, n: struct.unpack("<%df" % n, pe.read(va, 4 * n))
    step = f32(0x864038, 1)[0]
    forms = [
        ("sin", f32(0x84E004, 10241), lambda i: math.sin(i * 2 * math.pi / 8192)),
        ("asin", f32(0x858014, 4097), lambda i: math.asin(max(-1.0, min(1.0, i / 2048 - 1)))),
        ("tan", f32(0x85C024, 4097), lambda i: math.tan(i * 2 * math.pi / 4096)),
        ("atan", f32(0x860034, 4097), lambda i: math.atan(i * step)),
    ]
    for name, tab, fn in forms:
        bad = sum(1 for i in range(len(tab)) if tab[i] != rf(fn(i)))
        print("%-5s %5d entries, %5d differ from the correctly rounded closed form" % (name, len(tab), bad))


def main(argv):
    if len(argv) >= 2 and argv[1] == "--check-formula":
        check_formula(Pe(argv[2]))
        return 0
    if len(argv) != 3:
        print(__doc__)
        return 2
    pe = Pe(argv[1])
    if pe.sha1 != EXPECTED_SHA1:
        print("WARNING: SHA-1 %s != the RE build %s; addresses may not apply" % (pe.sha1, EXPECTED_SHA1))
        return 1
    emit(pe, argv[2])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
